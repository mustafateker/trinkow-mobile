/** Ordinal day of month: 1st, 2nd, 3rd, 4th … 11th, 12th, 13th … 21st, 22nd, 23rd … 31st. */
function sirali(gun: number): string {
  const sonIki = gun % 100;
  if (sonIki >= 11 && sonIki <= 13) return `${gun}th`;
  switch (gun % 10) {
    case 1:
      return `${gun}st`;
    case 2:
      return `${gun}nd`;
    case 3:
      return `${gun}rd`;
    default:
      return `${gun}th`;
  }
}

